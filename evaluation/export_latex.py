#!/usr/bin/env python3
"""Export selected JSON values as LaTeX commands.

Example:
  python export_latex.py --output ../../paper/generated_results.tex \
    --value SafeRE=results/safe.json:summary.mean.run_rate \
    --value TaskOneIRValid=results/task1.json:summary.ir_valid.rate
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


def lookup(payload, dotted: str):
    value = payload
    for component in dotted.split("."):
        if isinstance(value, list):
            value = value[int(component)]
        else:
            value = value[component]
    return value


def latex_escape(value) -> str:
    if isinstance(value, float):
        return f"{value:.2f}"
    return str(value).replace("%", r"\%").replace("_", r"\_")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument(
        "--value",
        action="append",
        default=[],
        metavar="MACRO=JSON:PATH",
        help="May be repeated.",
    )
    args = parser.parse_args()

    commands = {}
    for specification in args.value:
        try:
            macro, source = specification.split("=", 1)
            filename, dotted = source.rsplit(":", 1)
        except ValueError as exc:
            raise ValueError(f"Invalid --value {specification!r}") from exc
        if not re.fullmatch(r"[A-Za-z]+", macro):
            raise ValueError(f"LaTeX macro names must contain only letters: {macro}")
        payload = json.loads(Path(filename).read_text(encoding="utf-8"))
        commands[macro] = latex_escape(lookup(payload, dotted))

    args.output.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "% Auto-generated by project/evaluation/export_latex.py.",
        "% Re-run the exporter instead of editing this file by hand.",
    ]
    lines.extend(
        rf"\renewcommand{{\{macro}}}{{{value}}}"
        for macro, value in sorted(commands.items())
    )
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(commands)} macros to {args.output}")


if __name__ == "__main__":
    main()
